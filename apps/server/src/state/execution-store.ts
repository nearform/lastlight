export interface ExecutionRecord {
  id: string;
  triggerType: "webhook" | "cron" | "chat" | "api";
  triggerId: string;
  /**
   * Who triggered/acted on this execution (issue #205) — a GitHub login, a
   * Slack display name, or `cli`/`cron`/`admin`. Free-text; joined to `users`
   * on `login` for enrichment. Null on rows written before the column existed.
   */
  triggeredBy?: string;
  /** Coarse actor category for {@link triggeredBy}. */
  triggerActorType?: TriggerActorType;
  skill: string;
  /**
   * GitHub org/user that owns {@link repo}. Its own column since #279, so a
   * ledger row identifies its target without joining the run that owns it —
   * which chat and `build-cycle` rows don't have.
   */
  owner?: string;
  /** BARE repo name (no owner). See `state/repo-ref.ts` for the one rule. */
  repo?: string;
  issueNumber?: number;
  startedAt: string;
  finishedAt?: string;
  success?: boolean;
  error?: string;
  turns?: number;
  durationMs?: number;
  /**
   * Runtime session id (OpenCode `ses_…`) captured from the event stream.
   * Used by the dashboard to look up the session log for a given phase.
   */
  sessionId?: string;
  /** Total USD cost reported by the runtime on the final step. Zero under OAuth/subscription auth. */
  costUsd?: number;
  /** Fresh input tokens (no cache hit). */
  inputTokens?: number;
  /** Tokens that triggered a cache write. */
  cacheCreationInputTokens?: number;
  /** Tokens served from prompt cache. */
  cacheReadInputTokens?: number;
  /** Output tokens generated by the model. */
  outputTokens?: number;
  /** API-side duration (excludes orchestrator overhead). */
  apiDurationMs?: number;
  /** Result subtype, e.g. "success" or "error_max_turns". */
  stopReason?: string;
  /**
   * Which agentic-pi extensions (file-search / github / web-search) were active
   * for this execution. A real JSON column, so this travels as an OBJECT in
   * both directions and nothing on either side stringifies it.
   */
  extensionStatus?: ExtensionStatusMap;
  /**
   * agentic-pi's skill-loading status for this execution (which skills were
   * discovered/available). A real JSON column, like {@link extensionStatus}.
   * Absent when the run reported no skills.
   */
  skillsStatus?: SkillsStatus;
  /**
   * Workflow run that owns this execution. Scopes dedup: a fresh re-trigger
   * creates a new workflow_run_id, so `shouldRunPhase` won't find matching
   * rows from the prior run and will correctly run the phase again.
   */
  workflowRunId?: string;
}

/**
 * Owns every read/write against the `executions` table — the harness's
 * append-only ledger of agent runs. The dashboard derives phase status from
 * this table (primary source, ahead of the `phase_history` fallback), and the
 * runner's resume path skips already-completed phases via {@link shouldRunPhase}.
 *
 * Carved out of the old `StateDb` god-class (issue #97). Constructed from the
 * single shared Drizzle client so it sits in the same connection scope as the
 * other stores. It is never a transaction participant — no method takes a
 * `dbc` — because nothing else has to move atomically with a ledger append.
 */
/**
 * `executions.repo`, composed into the qualified `owner/repo` a user-facing
 * surface speaks — or NULL when it can't be (issues #169, #279).
 *
 * This used to reach for the owner by joining `workflow_runs` on
 * `workflow_run_id`, because the column was written in two shapes and
 * `executions` had no owner of its own. It now has one (#279), so the join is
 * gone and the answer is on the row.
 *
 * **NULL is the safe answer, and deliberate.** A consumer of this treats null
 * as "no repo, always visible"; returning a bare name instead would produce a
 * value that matches nothing in a qualified allow-list and would therefore
 * HIDE the row. It embeds the schema columns, which render fully qualified
 * (`"executions"."owner"`), so any raw query using it must select from
 * `executions` UNALIASED — the old `e` alias is gone.
 */
const QUALIFIED_REPO_SQL = qualifiedRepoSql(executions.owner, executions.repo, "null");


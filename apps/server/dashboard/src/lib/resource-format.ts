/**
 * Formatters for sandbox resource usage (issue: per-phase CPU / memory). CPU is
 * CPU TIME, not a percentage — the sum of every core's busy time — so a phase
 * pinning two cores for a minute reads `2.0m`.
 */

export function formatCpuSeconds(s: number): string {
  if (s < 60) return `${s.toFixed(1)}s`;
  if (s < 3600) return `${(s / 60).toFixed(1)}m`;
  return `${(s / 3600).toFixed(1)}h`;
}

export function formatBytes(n: number): string {
  if (n >= 1024 ** 3) return `${(n / 1024 ** 3).toFixed(1)} GiB`;
  if (n >= 1024 ** 2) return `${(n / 1024 ** 2).toFixed(0)} MiB`;
  if (n >= 1024) return `${(n / 1024).toFixed(0)} KiB`;
  return `${n} B`;
}
